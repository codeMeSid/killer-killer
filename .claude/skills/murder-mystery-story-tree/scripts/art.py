#!/usr/bin/env python3
"""Wrap a Hairline figure file into a story's art.ts, or unwrap it back.

Usage:
  python art.py wrap <figure.js> <art.ts> --slug <slug>
  python art.py unwrap <art.ts> <figure.js>

art.ts is the figure body verbatim inside `export default function define(HL, hairline) { ... }`, so the
hairline-create tooling (look.mjs, validate.mjs) still runs on the unwrapped file. Round trip is byte-for-byte
for any figure file ending in a newline (one is added if missing). See references/art.md.
"""
import argparse
import re
import sys
from pathlib import Path

OPEN = "export default function define(HL, hairline) {\n"
CLOSE = "}\n"
HEADER = (
    "// @ts-nocheck\n"
    '// Hairline figure "{name}" for {slug}. Generated by the murder-mystery-story-tree skill via hairline-create.\n'
    "// Body is the figure file verbatim; edit with: python scripts/art.py unwrap <this> {name}.js → look.mjs → wrap.\n"
)
NAME = re.compile(r"""hairline\(\{\s*name:\s*["']([^"']+)["']""")


def wrap(body, slug):
    names = NAME.findall(body)
    if not names:
        raise ValueError('no `hairline({ name: "..." ...})` call found in the figure')
    if not body.endswith("\n"):
        body += "\n"
    return HEADER.format(name=names[-1], slug=slug) + OPEN + body + CLOSE


def unwrap(text):
    head, sep, rest = text.partition(OPEN)
    if not sep or not head.startswith("// @ts-nocheck\n") or not rest.endswith(CLOSE):
        raise ValueError("not an art.ts written by art.py wrap")
    return rest[: -len(CLOSE)]


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    w = sub.add_parser("wrap")
    w.add_argument("figure")
    w.add_argument("art")
    w.add_argument("--slug", required=True)
    u = sub.add_parser("unwrap")
    u.add_argument("art")
    u.add_argument("figure")
    a = ap.parse_args()
    try:
        if a.cmd == "wrap":
            body = Path(a.figure).read_bytes().decode("utf-8")  # bytes: no newline translation
            out = wrap(body, a.slug)
            # the inverse must hold before anything is written
            assert unwrap(out) == (body if body.endswith("\n") else body + "\n"), "round trip failed"
            Path(a.art).write_bytes(out.encode("utf-8"))
            print(f"wrote {a.art}")
        else:
            Path(a.figure).write_bytes(unwrap(Path(a.art).read_bytes().decode("utf-8")).encode("utf-8"))
            print(f"wrote {a.figure}")
    except (OSError, ValueError) as exc:
        print("ERROR", exc)
        sys.exit(1)


if __name__ == "__main__":
    main()
